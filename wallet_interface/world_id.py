@dataclass(frozen=True)
class WorldIdRpSignature:
    """World ID RP signature payload generated by the backend."""

    signature: str
    nonce: str
    created_at: int
    expires_at: int
    action: str | None = None

    def to_protocol_dict(self) -> dict[str, object]:
        """Return the protocol field names used by World ID signing docs."""

        return {
            "sig": self.signature,
            "nonce": self.nonce,
            "created_at": self.created_at,
            "expires_at": self.expires_at,
        }

    def to_rp_context(self, rp_id: str) -> dict[str, object]:
        """Return an IDKit-ready RP context with the relying-party ID."""

        return {
            "rp_id": rp_id,
            **self.to_protocol_dict(),
        }


