def _parse_private_key(value: str) -> bytes:
    raw = str(value or "").strip()
    if raw.startswith("0x"):
        raw = raw[2:]
    try:
        key = bytes.fromhex(raw)
    except ValueError as exc:
        raise WorldIdSignatureError("signing key must be 32 bytes of hex") from exc
    if len(key) != 32:
        raise WorldIdSignatureError("signing key must be 32 bytes")
    return key


def _parse_bytes32(value: bytes | str, name: str) -> bytes:
    if isinstance(value, str):
        raw = value.strip()
        if raw.startswith("0x"):
            raw = raw[2:]
        try:
            data = bytes.fromhex(raw)
        except ValueError as exc:
            raise WorldIdSignatureError(f"{name} must be 32 bytes of hex") from exc
    else:
        data = bytes(value)
    if len(data) != 32:
        raise WorldIdSignatureError(f"{name} must be exactly 32 bytes")
    return data


def _uint64(value: int, name: str) -> int:
    parsed = int(value)
    if parsed < 0 or parsed > 2**64 - 1:
        raise WorldIdSignatureError(f"{name} must fit uint64")
    return parsed


def _validate_base_url(value: str) -> str:
    normalized = str(value or "").strip().rstrip("/")
    parsed = urlparse(normalized)
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        raise WorldIdVerificationError("base URL must be an absolute http(s) URL")
    return normalized


def _default_world_id_request_json(
    method: str,
    url: str,
    payload: Mapping[str, Any],
    headers: Mapping[str, str],
    timeout_seconds: float,
) -> Mapping[str, Any]:
    request_body = json.dumps(payload).encode("utf-8")
    req = urllib_request.Request(
        url,
        data=request_body,
        headers=dict(headers),
        method=method,
    )
    try:
        with urllib_request.urlopen(req, timeout=timeout_seconds) as response:
            raw = response.read().decode("utf-8")
    except urllib_error.HTTPError as exc:
        raw_error = exc.read().decode("utf-8", errors="replace")
        raise WorldIdVerificationError(
            f"World ID verification request failed with status {exc.code}: {_redact_text(raw_error)}"
        ) from exc
    try:
        parsed = json.loads(raw or "{}")
    except Exception as exc:
        raise WorldIdVerificationError("World ID verification response was not valid JSON") from exc
    if not isinstance(parsed, Mapping):
        raise WorldIdVerificationError("World ID verification response must be a JSON object")
    return parsed


def _safe_error_message(exc: Exception) -> str:
    return _redact_text(str(exc))


def _redact_text(value: str, *, limit: int = 500) -> str:
    text = str(value or "")
    for marker in ("proof", "nullifier", "session_nullifier", "merkle_root", "signal_hash", "jwt"):
        if marker in text.lower():
            return "[redacted World ID verification error]"
    return text[:limit]
